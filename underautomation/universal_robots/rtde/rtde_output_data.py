from enum import IntEnum

class RtdeOutputData(IntEnum):
	Timestamp = 0 # Time elapsed since the controller was started [s]
	TargetQ = 1 # Target joint positions
	TargetQd = 2 # Target joint velocities
	TargetQdd = 3 # Target joint accelerations
	TargetCurrent = 4 # Target joint currents
	TargetMoment = 5 # Target joint moments (torques)
	ActualQ = 6 # Actual joint positions
	ActualQd = 7 # Actual joint velocities
	ActualCurrent = 8 # Actual joint currents
	JointControlOutput = 9 # Joint control currents
	ActualTcpPose = 10 # Actual Cartesian coordinates of the tool: (x,y,z,rx,ry,rz), where rx, ry and rz is a rotation vector representation of the tool orientation
	ActualTcpSpeed = 11 # Actual speed of the tool given in Cartesian coordinates. The speed is given in [m/s] and the rotational part of the TCP speed (rx, ry, rz) is the angular velocity given in [rad/s]
	ActualTcpForce = 12 # Generalized forces in the TCP. It compensates the measurement for forces and torques generated by the payload
	TargetTcpPose = 13 # Target Cartesian coordinates of the tool: (x,y,z,rx,ry,rz), where rx, ry and rz is a rotation vector representation of the tool orientation
	TargetTcpSpeed = 14 # Target speed of the tool given in Cartesian coordinates. The speed is given in [m/s] and the rotational part of the TCP speed (rx, ry, rz) is the angular velocity given in [rad/s]
	ActualDigitalInputBits = 15 # Current state of the digital inputs. 0-7: Standard, 8-15: Configurable, 16-17: Tool
	JointTemperatures = 16 # Temperature of each joint in degrees Celsius
	ActualExecutionTime = 17 # Controller real-time thread execution time
	RobotMode = 18 # Robot mode
	JointMode = 19 # Joint control modes
	SafetyMode = 20 # Safety mode
	SafetyStatus = 21 # Safety status
	ActualToolAccelerometer = 22 # Tool x, y and z accelerometer values
	SpeedScaling = 23 # Speed scaling of the trajectory limiter
	TargetSpeedFraction = 24 # Target speed fraction
	ActualMomentum = 25 # Norm of Cartesian linear momentum
	ActualMainVoltage = 26 # Safety Control Board: Main voltage
	ActualRobotVoltage = 27 # Safety Control Board: Robot voltage (48V)
	ActualRobotCurrent = 28 # Safety Control Board: Robot current
	ActualJointVoltage = 29 # Actual joint voltages
	ActualDigitalOutputBits = 30 # Current state of the digital outputs. 0-7: Standard, 8-15: Configurable, 16-17: Tool
	RuntimeState = 31 # Program state
	ElbowPosition = 32 # Position of robot elbow in Cartesian Base Coordinates
	ElbowVelocity = 33 # Velocity of robot elbow in Cartesian Base Coordinates
	RobotStatusBits = 34 # Bits 0-3:Is power on | Is program running | Is teach button pressed | Is power button pressed
	SafetyStatusBits = 35 # Bits 0-10: Is normal mode | Is reduced mode | Is protective stopped | Is recovery mode | Is safeguard stopped | Is system emergency stopped | Is robot emergency stopped | Is emergency stopped | Is violation | Is fault | Is stopped due to safety
	AnalogIOTypes = 36 # Bits 0-3: analog input 0 | analog input 1 | analog output 0 | analog output 1, {0=current[mA], 1=voltage[V]}
	StandardAnalogInput0 = 37 # Standard analog input 0 [mA or V]
	StandardAnalogInput1 = 38 # Standard analog input 1 [mA or V]
	StandardAnalogOutput0 = 39 # Standard analog output 0 [mA or V]
	StandardAnalogOutput1 = 40 # Standard analog output 1 [mA or V]
	IOCurrent = 41 # I/O current [mA]
	Euromap67InputBits = 42 # Euromap67 input bits
	Euromap67OutputBits = 43 # Euromap67 output bits
	Euromap67_24VVoltage = 44 # Euromap 24V voltage [V]
	Euromap67_24VCurrent = 45 # Euromap 24V current [mA]
	ToolMode = 46 # Tool mode
	ToolAnalogInputTypes = 47 # Output domain {0=current[mA], 1=voltage[V]} Bits 0-1: tool_analog_input_0 | tool_analog_input_1
	ToolAnalogInput0 = 48 # Tool analog input 0 [mA or V]
	ToolAnalogInput1 = 49 # Tool analog input 1 [mA or V]
	ToolOutputVoltage = 50 # Tool output voltage [V]
	ToolOutputCurrent = 51 # Tool current [mA]
	ToolTemperature = 52 # Tool temperature in degrees Celsius
	TcpForceScalar = 53 # TCP force scalar [N]
	OutputBitRegisters0To31 = 54 # General purpose bits
	OutputBitRegisters32To63 = 55 # General purpose bits
	OutputBitRegisters = 56 # 64 general purpose bits. X: [64..127] - The upper range of the boolean output registers can be used by external RTDE clients (i.e URCAPS).
	OutputIntRegisters = 57 # 48 general purpose integer registers. X: [0..23] - The lower range of the integer output registers is reserved for FieldBus/PLC interface usage. X: [24..47] - The upper range of the integer output registers can be used by external RTDE clients (i.e URCAPS).
	OutputDoubleRegisters = 58 # 48 general purpose double registers. X: [0..23] - The lower range of the double output registers is reserved for FieldBus/PLC interface usage. X: [24..47] - The upper range of the double output registers can be used by external RTDE clients (i.e URCAPS).
	InputBitRegisters0To31 = 59 # General purpose bits (input read back). This range of the boolean output registers is reserved for FieldBus/PLC interface usage.
	InputBitRegisters32To63 = 60 # General purpose bits (input read back), This range of the boolean output registers is reserved for FieldBus/PLC interface usage.
	InputBitRegisters = 61 # 64 general purpose bits, X: [64..127] - The upper range of the boolean output registers can be used by external RTDE clients (i.e URCAPS).
	InputIntRegisters = 62 # 48 general purpose integer registers. X: [0..23] - The lower range of the integer input registers is reserved for FieldBus/PLC interface usage. X: [24..47] - The upper range of the integer input registers can be used by external RTDE clients (i.e URCAPS).
	InputDoubleRegisters = 63 # 48 general purpose double registers. X: [0..23] - The lower range of the double input registers is reserved for FieldBus/PLC interface usage. X: [24..47] - The upper range of the double input registers can be used by external RTDE clients (i.e URCAPS).
	ToolOutputMode = 64 # The current output mode
	ToolDigitalOutput0mode = 65 # The current mode of digital output 0
	ToolDigitalOutput1Mode = 66 # The current mode of digital output 1
	Payload = 67 # Payload mass Kg
	PayloadCOG = 68 # Payload Center of Gravity (CoGx, CoGy, CoGz) m
	PayloadInertia = 69 # Payload inertia matrix elements (Ixx,Iyy,Izz,Ixy,Ixz,Iyz] expressed in kg*m^2
	ScriptControlLine = 70 # Script line number that is actually in control of the robot given the robot is locked by one of the threads in the script. If no thread is locking the robot this field is set to '0'. Script line number should not be confused with program tree line number displayed on polyscope.
	FTRawWrench = 71 # Raw force and torque measurement, not compensated for forces and torques caused by the payload
